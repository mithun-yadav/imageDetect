import { Injectable, InternalServerErrorException } from '@nestjs/common';

import { randomUUID } from 'node:crypto';
import { mkdir, unlink, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';

const MIME_EXTENSIONS: Record<string, string> = {
  'image/jpeg': '.jpg',
  'image/png': '.png',
  'image/webp': '.webp',
};

@Injectable()
export class StorageService {
  private readonly storagePath = resolve(process.env.UPLOAD_STORAGE_PATH ?? './uploads');

  async save(buffer: Buffer, mimeType: string): Promise<string> {
    const extension = MIME_EXTENSIONS[mimeType];

    if (!extension) {
      throw new InternalServerErrorException('Unsupported image MIME type for storage');
    }

    const storageKey = `${randomUUID()}${extension}`;
    const filePath = join(this.storagePath, storageKey);

    try {
      await mkdir(this.storagePath, {
        recursive: true,
        mode: 0o700,
      });

      await writeFile(filePath, buffer, {
        flag: 'wx',
        mode: 0o600,
      });

      return storageKey;
    } catch {
      throw new InternalServerErrorException('Unable to store uploaded image');
    }
  }

  async delete(storageKey: string): Promise<void> {
    // Only accept UUID-based image filenames generated by this service.
    const isValidKey =
      /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(jpg|png|webp)$/i.test(
        storageKey,
      );

    if (!isValidKey) {
      throw new InternalServerErrorException('Invalid image storage key');
    }

    const filePath = join(this.storagePath, storageKey);

    try {
      await unlink(filePath);
    } catch (error) {
      // Deleting an already-missing file is harmless.
      if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
        return;
      }

      throw new InternalServerErrorException('Unable to delete stored image');
    }
  }
}
